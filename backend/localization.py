MESSAGES = {row.split('|')[0]: tuple(row.split('|')[1:]) for row in ROWS.splitlines()}


def language(request):
    return 'kk' if request.headers.get('accept-language', '').startswith('kk') else 'ru'


def translate(value, lang, status=422):
    if not isinstance(value, str): return value
    index = 1 if lang == 'kk' else 0
    if ' / ' in value and len(value.split(' / ')) == 2:
        return value.split(' / ')[index]
    if value in MESSAGES: return MESSAGES[value][index]
    if lang == 'kk' and any(c in value for c in 'әғқңөұүһіӘҒҚҢӨҰҮҺІ'): return value
    if lang == 'ru' and any('\u0400' <= c <= '\u04ff' for c in value): return value
    if value.startswith('File is too large'):
        return ('Файл слишком большой. Максимум 15 МБ.', 'Файл тым үлкен. Ең көбі 15 МБ.')[index]
    if status == 404: return ('Запись не найдена', 'Жазба табылмады')[index]
    if status == 403: return ('Недостаточно прав для этого действия', 'Бұл әрекетке құқық жеткіліксіз')[index]
    if status == 409: return ('Такая запись уже существует', 'Мұндай жазба бұрыннан бар')[index]
    if status >= 500: return ('Операция не выполнена. Обратитесь к администратору.', 'Әрекет орындалмады. Әкімшіге хабарласыңыз.')[index]
    return ('Проверьте обязательные поля, даты и значения из справочников.', 'Міндетті өрістерді, күндер мен анықтамалық мәндерін тексеріңіз.')[index]


async def http_error(request: Request, exc: HTTPException):
    lang = language(request)
    detail = exc.detail
    if isinstance(detail, dict):
        detail = {**detail}
        for key in ('message', 'hint'):
            if key in detail: detail[key] = translate(detail[key], lang, exc.status_code)
    else:
        detail = translate(detail, lang, exc.status_code)
    return JSONResponse({'detail': detail}, status_code=exc.status_code, headers=exc.headers)


async def validation_error(request: Request, exc: RequestValidationError):
    lang = language(request)
    return JSONResponse({'detail': translate('', lang)}, status_code=422)
