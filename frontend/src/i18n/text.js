export function localizeText(value, lang = 'ru') {
  if (typeof value !== 'string') return value
  const pair = value.split(' / ')
  if (pair.length === 2) return pair[lang === 'kk' ? 1 : 0]
  let out = value
  for (const [en, ru, kk] of phrases) out = out.replaceAll(en, lang === 'kk' ? kk : ru)
  if (lang === 'kk') out = kkMessages[out] || out
  out = out.replace(/([\d.]+) y in company/g, lang === 'kk' ? 'Компанияда $1 жыл' : '$1 лет в компании')
    .replace(/([\d.]+) y total/g, lang === 'kk' ? 'Жалпы $1 жыл' : '$1 лет общего стажа')
    .replace(/([\d.]+) y in ([A-Z_]+)/g, lang === 'kk' ? '$2: $1 жыл' : '$2: $1 лет')
    .replace(/no ([A-Z_]+) experience/g, lang === 'kk' ? '$1 тәжірибесі жоқ' : 'Нет опыта: $1')
    .replace(/\(need ([^)]+)\)/g, lang === 'kk' ? '(қажет: $1)' : '(требуется: $1)')
  return out
}
